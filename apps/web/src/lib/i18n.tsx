export type AppCopy = typeof copy.es;

const I18nContext = createContext<I18nContextValue | null>(null);

function getInitialLocale(): AppLocale {
  if (typeof window === "undefined") {
    return "es";
  }

  const storedLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  if (storedLocale === "es" || storedLocale === "en") {
    return storedLocale;
  }

  return window.navigator.language.toLowerCase().startsWith("en") ? "en" : "es";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>(() => getInitialLocale());

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale: setLocaleState,
      t: copy[locale],
      dateLocale: locale === "en" ? "en-CA" : "es-MX",
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);

  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return value;
}

export function translatePinResultMessage(message: string, t: typeof copy.es) {
  if (message === copy.es.errors.invalidPin || message === copy.en.errors.invalidPin) {
    return t.errors.invalidPin;
  }

  if (message === copy.es.errors.lockedPin || message === copy.en.errors.lockedPin) {
    return t.errors.lockedPin;
  }

  return message;
}
